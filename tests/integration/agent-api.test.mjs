// After ordered 0031 application, run next start -p 3105 with the existing fake
// model API, then: node --import tsx --env-file=.env.local --test tests/integration/agent-api.test.mjs
import assert from 'node:assert/strict';
import test from 'node:test';
import { admin, user } from '../db/helpers.mjs';
import { createToken } from '../../src/lib/agents/tokens.ts';
const origin = 'http://127.0.0.1:3105';
async function rpc(token, name, args, id = 1) {
  const response = await fetch(`${origin}/mcp`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${token}` },
    body: JSON.stringify({ jsonrpc: '2.0', id, method: 'tools/call', params: { name, arguments: args } }) });
  return { response, body: await response.json() };
}
test('MCP logs coffee with past eaten-at, isolates owners, revokes immediately and rate limits', async () => {
  const first = await user(1), second = await user(2), db = admin();
  const firstToken = await createToken(first.user.id, 'Integration agent', db);
  const secondToken = await createToken(second.user.id, 'Other integration agent', db);
  let postId;
  try {
    const eaten_at = new Date(Date.now() - 3600000).toISOString();
    const logged = await rpc(firstToken.token, 'log_meal', { caption: 'coffee', eaten_at });
    assert.equal(logged.response.status, 200); assert.ok(!logged.body.result.isError);
    const meal = JSON.parse(logged.body.result.content[0].text); postId = meal.id;
    const read = await rpc(firstToken.token, 'get_meal', { id: postId });
    assert.ok(!read.body.result.isError); assert.equal(JSON.parse(read.body.result.content[0].text).eaten_at, eaten_at);
    const other = await rpc(secondToken.token, 'get_meal', { id: postId });
    assert.equal(other.body.result.isError, true); assert.equal(other.body.result.content[0].text, 'Not found');
    const revoked = await first.client.from('agent_tokens').update({ revoked_at: new Date().toISOString() }).eq('id', firstToken.id);
    assert.equal(revoked.error, null);
    assert.equal((await rpc(firstToken.token, 'get_meal', { id: postId })).response.status, 401);
    // The second token already made one call. Batches consume every entry.
    const batch = await fetch(`${origin}/mcp`, { method: 'POST', headers: { 'Content-Type': 'application/json', Authorization: `Bearer ${secondToken.token}` },
      body: JSON.stringify(Array.from({ length: 59 }, (_, id) => ({ jsonrpc: '2.0', id, method: 'ping' }))) });
    assert.equal(batch.status, 200);
    assert.equal((await rpc(secondToken.token, 'list_meals', {})).response.status, 429);
    const missing = await fetch(`${origin}/api/agent/meals`);
    assert.equal(missing.status, 401);
  } finally {
    if (postId) {
      // Cards may have been generated by the fake worker; remove only this test
      // post's storage prefix before deleting its rows.
      const files = await db.storage.from('media').list(`${first.user.id}/${postId}`);
      if (files.error) throw files.error;
      const paths = (files.data ?? []).filter(file => file.id).map(file => `${first.user.id}/${postId}/${file.name}`);
      if (paths.length) await db.storage.from('media').remove(paths);
      const deleted = await db.from('posts').delete().eq('id', postId).eq('user_id', first.user.id);
      assert.equal(deleted.error, null);
    }
    await db.from('agent_tokens').delete().in('id', [firstToken.id, secondToken.id]);
    await first.client.auth.signOut({ scope: 'local' }); await second.client.auth.signOut({ scope: 'local' });
  }
});
