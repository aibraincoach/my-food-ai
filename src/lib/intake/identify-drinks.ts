import type {SupabaseClient} from '@supabase/supabase-js';
import {identifyItems} from '@/lib/meta/spark';
import {resolveFoodMatch} from '@/lib/fdc/match';
import {scaleNutrition} from '@/lib/fdc/nutrients';
import {isDrinkItem} from './drinks-from-items';
import {photoDrinkVolume} from './drink-volume';
import type {PhotoDrink,DrinkNutrition} from './photo-drinks';
import type {StoredNutrient} from '@/lib/nutrition/totals';
export type {PhotoDrink} from './photo-drinks';
/** One ordinary Spark identify call, followed by the app's existing USDA matcher.
 * Spark estimates portions only; nutrition is never generated by the model. */
export async function identifyDrinks(admin:SupabaseClient,_userId:string,photo:Uint8Array):Promise<{drinks:PhotoDrink[];allDrinks:boolean}> {
 const meal=await identifyItems(photo,'image/jpeg',null,[],`For a beverage, put its volume in ml in portion_text as well as an independently estimated portion_grams. If an explicit package volume is visibly legible, append "read from the can" to portion_text; otherwise append "estimated from the photo". Do not infer a printed volume from a familiar package. Name every food as usual, including food that is not a drink. Plain water in a glass is named "Water". Do not invent nutrients.`);
 const drinks:PhotoDrink[]=[];
 for(const item of meal.items){
  const ml=photoDrinkVolume(item.portionText);if(ml===null)continue;
  const plainWater=/^(?:plain |tap |bottled |sparkling )?water(?:,? (?:glass|bottle|can))?$/i.test(item.name.trim());
  const food=plainWater?null:await resolveFoodMatch(admin,item.name);
  if(!plainWater&&!isDrinkItem({name:item.name,food_category:food?.foodCategory}))continue;
  const scaled=scaleNutrition(food,item.portionGrams);
  const nutrition:DrinkNutrition=plainWater?{calories:0,protein_g:0,carbs_g:0,fat_g:0,fibre_g:0,sugar_g:0,sodium_mg:0,micronutrients:[],source_ref:null,food_category:'Water'}:
   {calories:scaled.calories,protein_g:scaled.proteinG,carbs_g:scaled.carbsG,fat_g:scaled.fatG,fibre_g:scaled.fibreG,sugar_g:scaled.sugarG,sodium_mg:scaled.sodiumMg,micronutrients:scaled.micronutrients as StoredNutrient[],source_ref:scaled.sourceRef,food_category:scaled.foodCategory??null};
  const caffeine=nutrition.micronutrients.find(n=>n.nutrientId===1057);
  const caffeineMg=caffeine?(caffeine.value===null?null:Number(caffeine.value)):plainWater?0:/\b(?:coca[- ]?cola|coke|cola|pepsi)\b/i.test(item.name)?32*ml/330:null;
  // Preserve a measured USDA value (e.g. 29.7 mg) before considering the disclosed cola fallback.
  if(caffeineMg!==null&&!caffeine)nutrition.micronutrients.push({nutrientId:1057,nutrientName:'Caffeine',unitName:'MG',value:caffeineMg,basis:'portion'});
  nutrition.micronutrients=nutrition.micronutrients.filter(n=>n.nutrientId!==1051);
  nutrition.micronutrients.push({nutrientId:1051,nutrientName:'Water',unitName:'G',value:ml,basis:'portion'});
  const fromCan=/read from the can/i.test(item.portionText??'');
  const name=plainWater?(/bottl/i.test(item.name)?'Water, bottle':'Water, glass'):fromCan&&!/\b(?:can|bottle)\b/i.test(item.name)?`${item.name}, can`:item.name;
  drinks.push({name,ml,caffeineMg,kcal:nutrition.calories,source:fromCan?'read from the can':'estimated from the photo',grams:plainWater?null:item.portionGrams,nutrition});
 }
 return {drinks,allDrinks:meal.items.length>0&&drinks.length===meal.items.length};
}
