// Regenerate after npm install: node scripts/third-party.mjs
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const lock = JSON.parse(await readFile(path.join(root, 'package-lock.json'), 'utf8'));
const escape = (value) => String(value).replaceAll('|', '\\|').replaceAll(/\r?\n/g, ' ');
const rows = [];
for (const [location, entry] of Object.entries(lock.packages).sort(([a], [b]) => a.localeCompare(b))) {
  if (!location) continue;
  let manifest;
  let source = 'installed package.json';
  try {
    manifest = JSON.parse(await readFile(path.join(root, location, 'package.json'), 'utf8'));
  } catch (error) {
    if (error.code !== 'ENOENT' || !entry.optional) throw error;
    // npm omits platform-specific optional binaries on other operating systems.
    manifest = entry;
    source = 'lockfile (optional package not installed on this platform)';
  }
  const name = manifest.name ?? location.slice(location.lastIndexOf('node_modules/') + 13);
  const license = typeof manifest.license === 'object' ? manifest.license.type : manifest.license;
  rows.push(`| ${escape(name)} | ${escape(entry.version)} | ${escape(license ?? 'UNDECLARED — inspect upstream licence')} | ${source} |`);
}
await writeFile(path.join(root, 'THIRD_PARTY.md'), `# Third-party notices

The application source uses the MIT licence in [LICENSE](LICENSE). Third-party works retain their own licences and terms. This inventory does not replace the licence files distributed with each package.

## Fonts, data and services

- Manrope: SIL Open Font License 1.1. Font licence and copyright notices remain with the bundled font files.
- USDA FoodData Central: public-domain nutrition data. Nutrition values in the application come from this data source.
- Meta Muse Spark 1.3, SAM 3.1 and Muse Voice Transcribe 1.0: accessed as hosted services under Meta's applicable Model API terms. Their models are not distributed under this repository's MIT licence.
- Photo fixtures: see [fixture attributions](scripts/fixtures/ATTRIBUTION.md) for individual source and licence notices.

## npm packages

Generated by \`node scripts/third-party.mjs\` from \`package-lock.json\`. Licences are read from each installed package's \`package.json\`. Optional packages omitted by npm for this platform are explicitly labelled and use the lockfile's licence metadata. Runtime, development and transitive dependencies are included; duplicate package versions remain separate rows.

| Package | Locked version | Declared licence | Source |
| --- | --- | --- | --- |
${rows.join('\n')}
`);
console.log(`Wrote ${rows.length} package notices.`);
