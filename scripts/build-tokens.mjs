import { writeFile } from 'node:fs/promises';
import { tsImport } from 'tsx/esm/api';

// Load the authored TypeScript values through the existing TypeScript loader.
const { tokens } = await tsImport('../src/lib/theme/tokens.ts', import.meta.url);
const lines = ['/* Generated by scripts/build-tokens.mjs. Edit tokens.ts, not this file. */', '@theme {'];
for (const [name, value] of Object.entries(tokens.colors)) lines.push(`  --color-${name}: ${value};`);
for (const [name, value] of Object.entries(tokens.typography)) {
  lines.push(`  --text-${name}: ${value.size}px;`, `  --text-${name}--font-weight: ${value.weight};`,
    `  --text-${name}--letter-spacing: ${value.tracking}px;`, `  --text-${name}--line-height: ${value.leading};`);
}
for (const [name, value] of Object.entries(tokens.spacing)) lines.push(`  --spacing-${name}: ${value}px;`);
for (const [name, value] of Object.entries(tokens.radii)) lines.push(`  --radius-${name}: ${value}px;`);
lines.push(`  --animate-shimmer: shimmer ${tokens.motion.shimmerSeconds}s linear infinite;`, '}', '');
await writeFile(new URL('../src/lib/theme/tokens.css', import.meta.url), lines.join('\n'));
